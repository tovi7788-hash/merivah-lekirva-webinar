export function calculateQuizScore(answers: readonly number[]): number | null {
  if (answers.length !== quizQuestions.length) return null;
  let total = 0;
  for (const answer of answers) {
    const weight = answerWeights[answer];
    if (!Number.isInteger(answer) || weight === undefined) return null;
    total += weight;
  }
  return total;
}

export function getQuizResult(score: number) {
  if (!Number.isFinite(score) || score < 0 || score > 20) return null;
  return quizResults.find((result) => score >= result.min) ?? null;
}